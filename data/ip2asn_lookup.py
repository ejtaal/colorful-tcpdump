#!/usr/bin/env python3
"""
ip2asn_lookup.py - A GeoIP/ASN lookup module based on ip2asn-combined.tsv + DB-IP City Lite

This module replaces the deprecated maxminddb_geolite2 (geomind) module with
a combination of:
- ip2asn-combined.tsv for ASN and country data
 - DB-IP's City Lite mmdb (free, CC BY 4.0, download with data/dbip-city.sh)
   for city/subdivision data, or the parsed dbip-city-ctd-data.bin.gz
   (generated by data/dbip-city-parse.py) when no mmdb is present

Usage:
    from ip2asn_lookup import ip2asn
    reader = ip2asn.reader()
    result = reader.get('1.1.1.1')
    print(result)
    reader.close()
"""

import ipaddress
import array
import bisect
import glob
import gzip
import json
import os
import re
import sys
import time
import threading

import radix
import maxminddb


# Spinner animation for loading progress
spinner_frames = ['\u2814', '\u2818', '\u2819', '\u281C', '\u2824', '\u282C', '\u2836', '\u2837', '\u2837', '\u283F']
spinner_idx = 0
_last_draw = 0.0
loading_stage = ["Loading ASN data..."]

def _set_loading_stage(stage):
    """Set the current loading stage text."""
    loading_stage[0] = stage

def _format_progress(percent):
    """Format a progress bar based on percentage."""
    width = 40
    filled = int(width * percent / 100)
    bar = '█' * filled + '░' * (width - filled)
    return f' [{bar}] {percent:3.0f}%'


def _show_spinner_step(progress=0):
    """Draw a spinner frame + progress bar, throttled to ~20 fps.

    Never sleeps: safe to call from inside tight loops (the time-based
    throttle keeps redraw cost negligible), so long blocking phases can
    report real progress instead of leaving the bar stuck.
    """
    global spinner_idx, _last_draw
    now = time.monotonic()
    if now - _last_draw < 0.05:
        return
    _last_draw = now
    spinner_idx += 1
    progress_str = _format_progress(progress)
    sys.stderr.write('\r' + spinner_frames[spinner_idx % len(spinner_frames)] + ' ' + loading_stage[0] + progress_str)
    sys.stderr.flush()


def _clear_spinner():
    """Erase the spinner line."""
    sys.stderr.write('\r' + ' ' * 80 + '\r')
    sys.stderr.flush()


class _IP2ASNReader:
    """Reader for ip2asn-combined.tsv + DB-IP City Lite data using radix trees for fast lookups."""

    def __init__(self, data_dir=None):
        """Initialize the reader by loading and indexing the data files.
        
        Args:
            data_dir: Directory containing the data files.
                      Defaults to the 'data' subdirectory next to this file.
        """
        self._asn_tree = radix.Radix()
        self._city_reader = None
        self._city_groups = []
        self._city_v4 = None
        self._city_v6 = None
        
        if data_dir is None:
            # Look for the data files in the same directory as this module
            script_dir = os.path.dirname(os.path.abspath(__file__))
            data_dir = script_dir
        
        self._data_dir = data_dir
        
        # Load ASN/country data from TSV
        tsv_path = os.path.join(data_dir, 'ip2asn-combined.tsv')
        if os.path.exists(tsv_path):
            self._load_asn_data(tsv_path)
        else:
            print(f"Warning: Could not find {tsv_path}", file=sys.stderr)
        
        # Load city data (optional): mmdb preferred, parsed binary as fallback
        self._open_city_data(data_dir)

    def _open_city_data(self, data_dir):
        """Load city data: newest DB-IP City Lite mmdb, else the parsed binary.

        Supported mmdb files (newest mtime wins):
            dbip-city-lite-<date>.mmdb / .mmdb.gz  (data/dbip-city.sh)
        A bundled .mmdb.gz is decompressed once, to .mmdb, on first use.

        Without a local mmdb, dbip-city-ctd-data.bin.gz (generated by
        data/dbip-city-parse.py from the mmdb, safe to redistribute under
        CC BY 4.0 with attribution) is loaded into sorted arrays instead:
        JSON CIDR lists plus a radix tree would need ~8 GB RAM for the
        ~13M ranges, the array/bisect approach needs ~300 MB.
        """
        mmdb_files = glob.glob(os.path.join(data_dir, 'dbip-city-lite-*.mmdb*'))
        if mmdb_files:
            self._city_reader = self._open_city_mmdb(data_dir, mmdb_files)
            if self._city_reader:
                return

        bin_path = os.path.join(data_dir, 'dbip-city-ctd-data.bin.gz')
        if os.path.exists(bin_path):
            self._load_city_binary(bin_path)
            return

        print("No city data found (city lookups disabled; run data/dbip-city.sh "
              "to get one)", file=sys.stderr)

    def _load_city_binary(self, bin_path):
        """Load city data from the parsed binary into sorted arrays.

        File format (see data/dbip-city-parse.py): a JSON header line,
        then v4 (u32 start, u32 end, u32 group) and v6 (16-byte packed
        start, 16-byte packed end, u32 group) range arrays, all
        little-endian, all sorted by start. Ranges are disjoint, so
        lookups are a binary search (bisect for v4).
        """
        _set_loading_stage("Loading city database...")

        for pct in range(45, 61, 2):
            _show_spinner_step(pct)
        _show_spinner_step(70)

        try:
            # 45-60%: open and read the header line, which tells us the
            # expected payload size so decompression can report progress.
            for pct in (45, 55):
                _show_spinner_step(pct)

            with gzip.open(bin_path, 'rb') as f:
                header = json.loads(f.readline())
                groups = header.get('groups', [])
                n4 = header.get('n4', 0)
                n6 = header.get('n6', 0)
                expected = 12 * n4 + 36 * n6

                # 60-90%: decompress in chunks, reporting real progress
                payload = bytearray()
                while True:
                    chunk = f.read(1 << 20)
                    if not chunk:
                        break
                    payload += chunk
                    _show_spinner_step(60 + 30 * min(1.0, len(payload) / max(1, expected)))

            # 90-100%: array construction (fast memcpy-level work)
            for pct in (90, 95, 100):
                _show_spinner_step(pct)

            # array('I').frombytes is native-endian; byteswap to fix on
            # big-endian hosts (the file is little-endian).
            def u32_le(buf):
                arr = array.array('I')
                arr.frombytes(buf)
                if sys.byteorder != 'little':
                    arr.byteswap()
                return arr

            off = 0
            starts4 = u32_le(payload[off:off + 4 * n4]); off += 4 * n4
            ends4 = u32_le(payload[off:off + 4 * n4]); off += 4 * n4
            gids4 = u32_le(payload[off:off + 4 * n4]); off += 4 * n4
            starts6 = payload[off:off + 16 * n6]; off += 16 * n6
            ends6 = payload[off:off + 16 * n6]; off += 16 * n6
            gids6 = u32_le(payload[off:off + 4 * n6]); off += 4 * n6

            self._city_groups = groups
            self._city_v4 = (starts4, ends4, gids4, n4)
            self._city_v6 = (starts6, ends6, gids6, n6)
            _clear_spinner()
            print(f"Loaded city data from {bin_path} "
                  f"({n4 + n6:,} ranges)", file=sys.stderr)
        except Exception as e:
            _clear_spinner()
            print(f"Warning: Could not load city data {bin_path}: {e}",
                  file=sys.stderr)

    def _open_city_mmdb(self, data_dir, mmdb_files=None):
        """Open the newest DB-IP City Lite mmdb found next to the other data files.

        Supported files (newest mtime wins):
            dbip-city-lite-<date>.mmdb / .mmdb.gz  (data/dbip-city.sh)
        A bundled .mmdb.gz is decompressed once, to .mmdb, on first use.
        """
        if mmdb_files is None:
            mmdb_files = glob.glob(os.path.join(data_dir, 'dbip-city-lite-*.mmdb*'))
        if not mmdb_files:
            return None

        chosen = max(mmdb_files, key=os.path.getmtime)

        if chosen.endswith('.gz'):
            unpacked = chosen[:-3]
            if unpacked in mmdb_files:
                # Both the .gz and its unpacked copy are present (e.g. after a
                # re-download): just use the unpacked copy.
                chosen = unpacked
            else:
                print(f"Decompressing {chosen} -> {unpacked} ...", file=sys.stderr)
                with gzip.open(chosen, 'rb') as src, open(unpacked, 'wb') as dst:
                    while True:
                        chunk = src.read(1 << 20)
                        if not chunk:
                            break
                        dst.write(chunk)
                chosen = unpacked

        try:
            # Set loading stage
            _set_loading_stage("Loading city database...")

            _show_spinner_step(60)
            reader = maxminddb.open_database(chosen)

            _show_spinner_step(90)

            # Clear spinner before showing final message
            _clear_spinner()
            print(f"Loaded city data from {chosen}", file=sys.stderr)
            return reader
        except Exception as e:
            _clear_spinner()
            print(f"Warning: Could not load city database {chosen}: {e}", file=sys.stderr)
            return None
    
    def _load_asn_data(self, tsv_path):
        """Load ASN/country data from TSV or preprocessed JSON, and build radix tree."""
        # Set loading stage
        _set_loading_stage("Loading ASN data...")
        
        # Try to load from preprocessed JSON first
        json_path = os.path.join(self._data_dir, 'ip2asn-ctd-data.json')
        if os.path.exists(json_path):
            count = self._load_asn_from_json(json_path)
        else:
            count = self._load_asn_from_tsv(tsv_path)
        
        # Show 45% complete for ASN loading
        _show_spinner_step(45)

        # Clear spinner before showing final message
        _clear_spinner()
        print(f"Loaded {count} ASN ranges", file=sys.stderr)
    
    def _load_asn_from_tsv(self, tsv_path):
        """Load ASN/country data from TSV and build radix tree. Returns count."""
        count = 0
        lines_processed = 0
        
        # Count total lines for progress
        try:
            with open(tsv_path, 'r') as f:
                total_lines = sum(1 for _ in f)
        except:
            total_lines = None
        
        # Show spinner while loading
        with open(tsv_path, 'r') as f:
            for line in f:
                lines_processed += 1
                
                # Update progress every 20000 lines
                if lines_processed % 20000 == 0 or total_lines is None:
                    if total_lines and total_lines > 0:
                        progress = (lines_processed / total_lines) * 45
                    else:
                        progress = min(45, lines_processed / 10000)
                    _show_spinner_step(progress)
                
                line = line.strip()
                if not line:
                    continue
                
                parts = line.split('\t')
                if len(parts) < 5:
                    continue
                
                start_ip_str, end_ip_str, asn_str, country_code, asn_name = \
                    parts[0], parts[1], parts[2], parts[3], parts[4]
                
                try:
                    start_ip = ipaddress.ip_address(start_ip_str)
                    end_ip = ipaddress.ip_address(end_ip_str)
                    
                    if start_ip == end_ip:
                        prefix_len = start_ip.max_prefixlen
                    else:
                        prefix_len = self._common_prefix_bits(start_ip, end_ip)
                    
                    if isinstance(start_ip, ipaddress.IPv4Address):
                        network = ipaddress.IPv4Network(f"{start_ip}/{prefix_len}", strict=False)
                    else:
                        network = ipaddress.IPv6Network(f"{start_ip}/{prefix_len}", strict=False)
                    
                    asn = int(asn_str) if asn_str.isdigit() else 0
                    country = country_code if country_code and country_code != 'None' else None
                    name = asn_name if asn_name and asn_name != 'Not routed' else None
                    
                    node = self._asn_tree.add(str(network))
                    node.data['country_code'] = country
                    node.data['asn'] = asn
                    node.data['asn_name'] = name
                    
                    count += 1
                    
                except (ValueError, IndexError):
                    continue
        
        return count
    
    def _load_asn_from_json(self, json_path):
        """Load ASN/country data from preprocessed JSON and build radix tree. Returns count."""
        count = 0

        # Stream the file so the (large) read can report progress 10->30%
        total = os.path.getsize(json_path)
        buf = bytearray()
        with open(json_path, 'rb') as f:
            while True:
                chunk = f.read(1 << 20)
                if not chunk:
                    break
                buf += chunk
                _show_spinner_step(10 + 20 * len(buf) / max(1, total))

        # Show spinner while parsing
        _show_spinner_step(30)
        data = json.loads(bytes(buf))
        del buf

        entries = data.get('data', {})
        n_entries = max(1, len(entries))

        # Build radix tree from JSON data, reporting real progress 30->45%
        for i, (key, entry) in enumerate(entries.items()):
            asn = entry.get('asn', 0)
            country = entry.get('country')
            name = entry.get('name')

            # Pass CIDR strings straight to py-radix: it parses them in C.
            # (Converting via ipaddress.ip_network first, only to call
            # str() again, used to cost several seconds here.)
            for cidr in entry.get('ranges', []):
                try:
                    node = self._asn_tree.add(cidr)
                    node.data['country_code'] = country
                    node.data['asn'] = asn
                    node.data['asn_name'] = name
                except ValueError:
                    continue
            count += 1
            if i % 500 == 0:
                _show_spinner_step(30 + 15 * i / n_entries)

        _show_spinner_step(45)
        return count
    
    def _common_prefix_bits(self, start_ip, end_ip):
        """Calculate the number of common prefix bits between two IP addresses."""
        start_int = int(start_ip)
        end_int = int(end_ip)
        
        xor = start_int ^ end_int
        
        if xor == 0:
            return start_ip.max_prefixlen
        
        prefix_len = start_ip.max_prefixlen - xor.bit_length()
        return prefix_len
    
    def _get_city_info(self, ip):
        """Get city/subdivision info from the DB-IP City Lite database."""
        if self._city_reader:
            return self._get_city_info_mmdb(ip)
        if self._city_v4 or self._city_v6:
            return self._get_city_info_arrays(ip)
        return None

    def _get_city_info_mmdb(self, ip):
        """Get city/subdivision info from the DB-IP City Lite mmdb."""
        if not self._city_reader:
            return None
        
        try:
            result = self._city_reader.get(str(ip))
            if not result:
                return None
            
            city_info = {}
            
            # Get country (only used for ranges the ASN table is missing)
            country = result.get('country')
            if country and country.get('iso_code'):
                city_info['country'] = country['iso_code']
            
            # Get city name
            city = result.get('city')
            if city and city.get('names'):
                # Drop parenthetical qualifiers such as 'Amsterdam (Amsterdam City
                # Centre)': they tend to make truncated display strings ugly.
                city_info['city'] = re.sub(r'\s*\([^)]*\)\s*', '', city['names'].get('en', '')).strip()
            
            # Get subdivision (state/region)
            subdivisions = result.get('subdivisions', [])
            if subdivisions and subdivisions[0].get('names'):
                city_info['subdivision'] = subdivisions[0]['names'].get('en', '')
            
            return city_info if city_info else None
        except Exception:
            return None

    def _get_city_info_arrays(self, ip):
        """Get city/subdivision info from the parsed binary arrays."""
        try:
            ip_obj = ipaddress.ip_address(ip)
        except ValueError:
            return None

        if isinstance(ip_obj, ipaddress.IPv4Address):
            starts, ends, gids, n = self._city_v4 or (None, None, None, 0)
            if not n:
                return None
            key = int(ip_obj)
            # Ranges are disjoint and sorted: the rightmost start <= key
            idx = bisect.bisect_right(starts, key) - 1
            if idx < 0 or key > ends[idx]:
                return None
            gid = gids[idx]
        else:
            starts, ends, gids, n = self._city_v6 or (None, None, None, 0)
            if not n:
                return None
            key = ip_obj.packed  # 16 bytes, big-endian = numeric order
            # Manual binary search over the packed start-address blob
            lo, hi = 0, n
            while lo < hi:
                mid = (lo + hi) >> 1
                if starts[mid * 16:mid * 16 + 16] <= key:
                    lo = mid + 1
                else:
                    hi = mid
            idx = lo - 1
            if idx < 0 or key > ends[idx * 16:idx * 16 + 16]:
                return None
            gid = gids[idx]

        try:
            cc, subdivision, city = self._city_groups[gid].split('|', 2)
        except (IndexError, ValueError):
            return None
        city_info = {}
        if cc:
            city_info['country'] = cc
        if city:
            city_info['city'] = city
        if subdivision:
            city_info['subdivision'] = subdivision
        return city_info if city_info else None
    
    def get(self, ip):
        """Look up IP address info.
        
        Args:
            ip: IP address string to look up
            
        Returns:
            Dictionary with country, city, subdivision, and ASN info:
            {
                'country': {'iso_code': 'US'},
                'subdivisions': [{'iso_code': 'CA'}],
                'asn': 13335,
                'name': 'CLOUDFLARENET - Cloudflare, Inc.',
                'city': 'Los Angeles',
                'subdivision': 'California'
            }
        """
        try:
            ipaddress.ip_address(ip)
        except ValueError:
            return None
        
        result = {}
        
        # Get ASN/country data from radix tree
        nodes = self._asn_tree.search_covering(str(ip))
        if nodes:
            best_node = max(nodes, key=lambda n: n.prefixlen)
            
            if best_node.data.get('country_code'):
                result['country'] = {'iso_code': best_node.data['country_code']}
            
            if best_node.data.get('asn') and best_node.data['asn'] > 0:
                result['asn'] = best_node.data['asn']
            
            if best_node.data.get('asn_name'):
                result['name'] = best_node.data['asn_name']
        
        # Get city data from mmdb
        city_info = self._get_city_info(ip)
        if city_info:
            # Fill in country from the city database only when the ASN table
            # is missing (or routing-blind for) this range.
            if 'country' not in result and city_info.get('country'):
                result['country'] = {'iso_code': city_info['country']}
            if city_info.get('city'):
                result['city'] = {'names': {'en': city_info['city']}}
            if city_info.get('subdivision'):
                result['subdivision'] = city_info['subdivision']
                result.setdefault('subdivisions', [
                    {'iso_code': '', 'names': {'en': city_info['subdivision']}}
                ])
        
        return result if result else None
    
    def close(self):
        """Close the reader and free resources."""
        self._asn_tree = None
        self._city_groups = []
        self._city_v4 = None
        self._city_v6 = None
        if self._city_reader:
            self._city_reader.close()
            self._city_reader = None


class geolite2:
    """Compatibility wrapper for maxminddb_geolite2 geolite2 module."""
    
    _reader = None
    
    @classmethod
    def reader(cls):
        """Get or create the reader instance."""
        if cls._reader is None:
            cls._reader = _IP2ASNReader()
        return cls._reader
    
    @classmethod
    def close(cls):
        """Close the reader."""
        if cls._reader:
            cls._reader.close()
            cls._reader = None
